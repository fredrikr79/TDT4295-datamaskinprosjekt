package palette_pkg;
  localparam int unsigned PaletteEntries = 256;
  localparam int unsigned PaletteIndexBits = $clog2(PaletteEntries);  // 8
  typedef logic unsigned [PaletteIndexBits-1:0] palette_index_t;

  function automatic color_lookup(input logic [7:0] pixel);
    case (material_t'(pixel[7:4]))
      MatAir:     return air_colors(pixel[3:0]);
      MatStone:   return stone_colors(pixel[3:0]);
      MatSand:    return sand_colors(pixel[3:0]);
      MatIgneous: return igneous_colors(pixel[3:0]);
      MatWater:   return water_colors(pixel[3:0]);
      MatLava:    return lava_colors(pixel[3:0]);
      MatAcid:    return acid_colors(pixel[3:0]);
      MatGOL:     return gol_colors(pixel[3:0]);
      MatExplo:   return explo_colors(pixel[3:0]);
    endcase
  endfunction

  function automatic explo_colors (input logic [3:0] meta);

    // based on an approximate 565 conversion of the 888 formula
    // Red = 60 + 13 * meta
    // Green = 11 * meta
    // blue = meta
    // Conversion done by (888_format / 255 * 31 (or 63 for green channel))
    // This function was generated by Claude Opus 5.5.
    // As none of us are creative artists with intuition for explosion colors.

    unique case (meta)
      0000: return 16'b00111_000000_00000; // 7_0_0
      0001: return 16'b01001_000011_00000; // 9_3_0
      0010: return 16'b01010_000101_00000; // 10_5_0
      0011: return 16'b01100_001000_00000; // 12_8_0
      0100: return 16'b01110_001011_00000; // 14_11_0
      0101: return 16'b01111_001110_00001; // 15_14_1
      0110: return 16'b10001_010000_00001; // 17_16_1
      0111: return 16'b10010_010011_00001; // 18_19_1
      1000: return 16'b10100_010110_00001; // 20_22_1
      1001: return 16'b10110_011000_00001; // 22_24_1
      1010: return 16'b10111_011011_00001; // 23_27_1
      1011: return 16'b11001_011110_00001; // 25_30_1
      1100: return 16'b11010_100001_00001; // 26_33_1
      1101: return 16'b11100_100011_00010; // 28_ 35_2
      1110: return 16'b11101_100110_00010; // 29_38_2
      1111: return 16'b11111_101001_00010; // 31_41_2
    endcase
  endfunction

  function automatic gol_colors (input logic [3:0] meta);
    unique case (meta[3])
      0: return 16'b11100_111001_11100; // of white
      1: return 16'b01110_011000_01100; // red-ish gray
    endcase
  endfunction

