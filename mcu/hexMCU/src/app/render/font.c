/* font.c - lookups for the fonts tools/ttf2c.py makes (see font.h). */

#include <stddef.h>

#include "font.h"

static const font_glyph_t *find(const font_t *f, uint32_t cp)
{
    /* ASCII: the generator puts 32..126 first, in order */
    if (cp >= 32 && cp <= 126 && (uint32_t)f->count > cp - 32 && f->glyphs[cp - 32].cp == cp)
        return &f->glyphs[cp - 32];

    /* the rest (ÆØÅæøå ...) is a short sorted list after that */
    for (uint16_t i = 0; i < f->count; i++)
        if (f->glyphs[i].cp == cp) return &f->glyphs[i];
    return NULL;
}

const font_glyph_t *font_glyph(const font_t *f, uint32_t cp)
{
    const font_glyph_t *g = find(f, cp);
    if (!g) g = find(f, '?');
    if (!g) g = &f->glyphs[0];
    return g;
}

bool font_pixel(const font_t *f, const font_glyph_t *g, int x, int y)
{
    if (x < 0 || y < 0 || y >= f->height || x >= 8 * f->row_bytes) return false;
    size_t i = (size_t)(g - f->glyphs);
    const uint8_t *row = f->bits + (i * f->height + (size_t)y) * f->row_bytes;
    return (row[x >> 3] >> (x & 7)) & 1u;
}

uint32_t font_utf8_next(const char **s)
{
    const unsigned char *p = (const unsigned char *)*s;
    uint32_t cp;
    int more;

    if (p[0] == 0) return 0;
    if      (p[0] < 0x80)           { cp = p[0];        more = 0; }
    else if ((p[0] & 0xE0) == 0xC0) { cp = p[0] & 0x1F; more = 1; }
    else if ((p[0] & 0xF0) == 0xE0) { cp = p[0] & 0x0F; more = 2; }
    else if ((p[0] & 0xF8) == 0xF0) { cp = p[0] & 0x07; more = 3; }
    else                            { *s += 1; return '?'; }

    for (int i = 1; i <= more; i++) {
        if ((p[i] & 0xC0) != 0x80) { *s += i; return '?'; }   /* cut short */
        cp = (cp << 6) | (p[i] & 0x3F);
    }
    *s += 1 + more;
    return cp;
}

int font_text_width(const font_t *f, const char *s)
{
    int w = 0;
    uint32_t cp;
    while ((cp = font_utf8_next(&s)) != 0)
        w += font_glyph(f, cp)->width;
    return w;
}


